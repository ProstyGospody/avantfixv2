const BUILDERS: Record<CitySlug, Builder> = { belgorod, oskol, gubkin };

export function faultCopy(appliance: Appliance, fault: Fault, city: City): FaultCopy {
  return BUILDERS[city.slug]({
    appliance,
    fault,
    city,
    workPrice: price(localPriceOf(fault.priceFrom, city)),
    time: duration(fault.durationMin),
  });
}
